def token_colours(p):
    def rule(name, scope, foreground, font_style=None):
        settings = {"foreground": foreground}
        if font_style is not None:
            settings["fontStyle"] = font_style
        return {"name": name, "scope": scope, "settings": settings}

    syntax, ink, muted = p["syntax"], p["ink"], p["muted"]
    return [
        rule("Comments", ["comment", "punctuation.definition.comment"], muted, "italic"),
        rule("Keywords", ["keyword", "storage.type", "storage.modifier", "keyword.control"], syntax["keyword"]),
        rule("Operators", ["keyword.operator", "punctuation.accessor"], muted),
        rule("Punctuation", ["punctuation", "meta.brace"], muted),
        rule("Strings", ["string", "punctuation.definition.string"], syntax["string"]),
        rule("String escapes and regexps", ["constant.character.escape", "string.regexp"], syntax["constant"]),
        rule("Numbers and constants", ["constant.numeric", "constant.language", "constant.other"], syntax["constant"]),
        rule("Functions", ["entity.name.function", "support.function", "meta.function-call entity.name.function"], syntax["function"]),
        rule("Types and classes", ["entity.name.type", "entity.name.class", "support.type", "support.class", "entity.other.inherited-class"], syntax["type"]),
        rule("Variables", ["variable", "meta.definition.variable"], ink),
        rule("Parameters", ["variable.parameter"], ink, "italic"),
        rule("Properties", ["variable.other.property", "variable.other.object.property", "support.variable.property", "meta.object-literal.key"], ink),
        rule("Language variables", ["variable.language"], syntax["keyword"], "italic"),
        rule("Annotations and decorators", ["meta.decorator", "storage.type.annotation", "entity.name.function.decorator"], syntax["constant"], "italic"),
        rule("Tags", ["entity.name.tag"], syntax["function"]),
        rule("Attributes", ["entity.other.attribute-name"], syntax["type"], "italic"),
        rule("Namespaces and imports", ["entity.name.namespace", "entity.name.module"], syntax["type"]),
        rule("Invalid", ["invalid", "invalid.illegal"], p["deleted"]),
        rule("Markdown headings", ["markup.heading", "entity.name.section.markdown"], syntax["keyword"], "bold"),
        rule("Markdown bold", ["markup.bold"], ink, "bold"),
        rule("Markdown italic", ["markup.italic"], ink, "italic"),
        rule("Markdown links", ["markup.underline.link", "string.other.link"], syntax["function"]),
        rule("Markdown code", ["markup.inline.raw", "markup.fenced_code"], syntax["constant"]),
        rule("Markdown quotes", ["markup.quote"], muted, "italic"),
        rule("Diff inserted", ["markup.inserted"], p["added"]),
        rule("Diff deleted", ["markup.deleted"], p["deleted"]),
        rule("Diff changed", ["markup.changed"], p["modified"]),
    ]


def semantic_colours(p):
    syntax = p["syntax"]
    return {
        "namespace": syntax["type"],
        "class": syntax["type"],
        "enum": syntax["type"],
        "interface": syntax["type"],
        "type": syntax["type"],
        "typeParameter": {"foreground": syntax["type"], "italic": True},
        "function": syntax["function"],
        "method": syntax["function"],
        "parameter": {"foreground": p["ink"], "italic": True},
        "property": p["ink"],
        "enumMember": syntax["constant"],
        "variable": p["ink"],
        "variable.readonly": p["ink"],
        "keyword": syntax["keyword"],
        "annotation": {"foreground": syntax["constant"], "italic": True},
        "decorator": {"foreground": syntax["constant"], "italic": True},
    }


def build(mode):
    p = PALETTES[mode]
    theme = {
        "name": p["name"],
        "type": p["type"],
        "semanticHighlighting": True,
        "colors": ui_colours(p),
        "tokenColors": token_colours(p),
        "semanticTokenColors": semantic_colours(p),
    }
    return THEMES_DIR / p["file"], theme


if __name__ == "__main__":
    THEMES_DIR.mkdir(exist_ok=True)
    for mode in PALETTES:
        path, theme = build(mode)
        path.write_text(json.dumps(theme, indent=2) + "\n")
        print(f"wrote {path}")
